/** Todos los ids de check de una capa — para calcular su semáforo. */
export function idsDeCapa(capa: Capa): string[] {
  return capa.grupos.flatMap(g => g.nodos.flatMap(n => n.checks.map(c => c.id)));
}

export function idsDeNodo(nodo: Nodo): string[] {
  return nodo.checks.map(c => c.id);
}

