/**
 * Contenido de la vista de águila de SIR Plus (Sistema Integral de Recaudación
 * remasterizado) — cuatro capas: Infraestructura, DevOps, DevSecOps y Sistema.
 *
 * IMPORTANTE sobre la naturaleza de estos datos:
 *   · Todo nace en estado "sin verificar". El panel NO afirma que algo exista o
 *     funcione: plantea qué hay que comprobar y con qué evidencia se comprueba.
 *   · `fuente` distingue de dónde sale cada punto:
 *       "zoho"    → tarea real registrada en Zoho (JAL-SIR+ o "aplica a todos
 *                   los proyectos"), o hecho tomado del tablero de operación.
 *       "codigo"  → comportamiento documentado en la Guía Funcional OPENSIR,
 *                   elaborada a partir del código fuente (rama dev-vps).
 *       "reco"    → recomendación de práctica, todavía no confirmada con el
 *                   equipo. Se debe validar antes de darla por cierta.
 */

export type Fuente = "zoho" | "codigo" | "reco";

export interface Check {
  id: string;
  /** Qué hay que reforzar o verificar. */
  label: string;
  /** Con qué se verifica y qué evidencia queda documentada. */
  verifica: string;
  fuente: Fuente;
}

export interface Nodo {
  id: string;
  nombre: string;
  resumen: string;
  /** La pregunta que este nodo debe poder responder de un vistazo. */
  pregunta?: string;
  checks: Check[];
}

export interface Grupo {
  id: string;
  nombre: string;
  nodos: Nodo[];
}

export interface Capa {
  id: string;
  nombre: string;
  sub: string;
  descripcion: string;
  color: string;
  grupos: Grupo[];
}

